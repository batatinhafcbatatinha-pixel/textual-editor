"""Generate a runnable Textual app from a design."""

from __future__ import annotations

import keyword
import re

from textual_editor.catalog import CATALOG, is_container
from textual_editor.model import Document, Node
from textual_editor.styles import quote_path

INDENT = "    "


def python_name(node_id: str) -> str:
    """A Python variable name for a node id."""
    name = re.sub(r"\W", "_", node_id)
    if not name or name[0].isdigit() or keyword.iskeyword(name):
        name = f"w_{name}"
    return name


def class_name(name: str) -> str:
    name = re.sub(r"\W", "", name) or "MyApp"
    return name if not name[0].isdigit() else f"App{name}"


def node_styles(document: Document, node: Node, parent: Node | None) -> dict[str, str]:
    """The CSS declarations for a node, including positioning."""
    styles = {name: value for name, value in node.styles.items() if str(value).strip()}
    docked = "dock" in styles or (node.type in CATALOG and CATALOG[node.type].docked)
    if parent is not None and document.is_free(parent) and not docked:
        styles = {"position": "absolute", **styles}
    else:
        styles.pop("offset", None)
    return styles


def generate_css(document: Document) -> str:
    rules: list[str] = []

    def rule(selector: str, styles: dict[str, str]) -> None:
        if not styles:
            return
        body = "\n".join(
            f"{INDENT}{name}: {quote_path(name, str(value).strip())};"
            for name, value in styles.items()
        )
        rules.append(f"{selector} {{\n{body}\n}}")

    rule("Screen", {name: value for name, value in document.root.styles.items() if str(value).strip()})

    def visit(node: Node) -> None:
        for child in node.children:
            rule(f"#{child.id}", node_styles(document, child, node))
            visit(child)

    visit(document.root)
    return "\n\n".join(rules)


def generate_compose(document: Document) -> list[str]:
    lines: list[str] = []

    def visit(node: Node, depth: int) -> None:
        indent = INDENT * depth
        for child in node.children:
            spec = CATALOG[child.type]
            code, attributes = spec.code(child)
            container = is_container(child.type)
            if attributes:
                variable = python_name(child.id)
                lines.append(f"{indent}{variable} = {code}")
                for name, value in attributes.items():
                    lines.append(f"{indent}{variable}.{name} = {value!r}")
                code = variable
            if container:
                lines.append(f"{indent}with {code}:")
                if child.children:
                    visit(child, depth + 1)
                else:
                    lines.append(f"{indent}{INDENT}pass")
            else:
                lines.append(f"{indent}yield {code}")

    visit(document.root, 2)
    return lines


def generate(document: Document) -> str:
    """Generate the source of a runnable Textual app."""
    modules: dict[str, set[str]] = {}
    for node in document.root.walk():
        if node.type in CATALOG:
            spec = CATALOG[node.type]
            modules.setdefault(spec.module, set()).add(spec.type)

    imports = ["from textual.app import App, ComposeResult"]
    for module in ("textual.containers", "textual.widgets"):
        if module in modules:
            imports.append(f"from {module} import {', '.join(sorted(modules[module]))}")

    css = generate_css(document)
    compose = generate_compose(document) or [f"{INDENT * 2}yield from ()"]
    name = class_name(document.class_name)

    source = [
        '"""Generated by textual-editor."""',
        "",
        *imports,
        "",
        "",
        f"class {name}(App):",
        f"{INDENT}TITLE = {document.title!r}",
    ]
    if css:
        css_body = "\n".join(f"{INDENT}{line}" if line else "" for line in css.splitlines())
        source += [f'{INDENT}CSS = """', css_body, f'{INDENT}"""']
    source += [
        "",
        f"{INDENT}def compose(self) -> ComposeResult:",
        *compose,
        "",
        "",
        'if __name__ == "__main__":',
        f"{INDENT}{name}().run()",
        "",
    ]
    return "\n".join(source)
